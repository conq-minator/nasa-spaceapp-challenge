"""M2.1 - Skyline sanity plots from data_out/ (no raw data needed).

For each site in data_out/sites.json:
  docs/skylines/<id>.png  - 2 m horizon (0.5 deg) vs azimuth, with a year of Sun and Earth
                            positions as faint dots; azimuths whose blocking terrain is more than
                            30.7 km away (outside the 3D far heightmap) are shaded.
  docs/skylines/README.md - one line per site, every number computed from data_out/.

Run from the repo root:   py -m Member2.pipeline.plot_skylines
                    or:   py Member2/pipeline/plot_skylines.py
"""
import json
import math
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data_out"
OUT = ROOT / "docs" / "skylines"
MESH_KM = 30.72          # far heightmap half-width (512 x 120 m / 2), from Member2 README
MAST = "2"


def circ_range(deg):
    """Smallest arc that contains all azimuths: returns (lo, hi) in 0..360 (lo may be > hi)."""
    a = np.sort(np.mod(deg, 360.0))
    gaps = np.diff(np.concatenate([a, [a[0] + 360.0]]))
    i = int(np.argmax(gaps))
    return float(a[(i + 1) % a.size]), float(a[i])


def horizon_at(h720, az):
    """Linear interpolation of a 0.5-deg horizon profile at azimuths az (deg)."""
    x = np.mod(np.asarray(az, float), 360.0) / 0.5
    i0 = np.floor(x).astype(int) % 720
    f = x - np.floor(x)
    return h720[i0] * (1 - f) + h720[(i0 + 1) % 720] * f


def site_summary(site, mask, ang):
    h720 = np.asarray(mask["elev_deg_720_by_mast"][MAST], float)
    dist = np.asarray(mask["horizon_dist_km_by_mast"][MAST], float)       # 360 bins
    i = int(np.argmax(h720))
    peak_az, peak_el = i * 0.5, float(h720[i])
    peak_km = float(dist[int(round(peak_az)) % 360])
    e_az = np.asarray(ang["earth_az"], float)
    e_el = np.asarray(ang["earth_el"], float)
    s_el = np.asarray(ang["sun_el"], float)
    lo, hi = circ_range(e_az)
    earth_ridge = horizon_at(h720, e_az)
    return {
        "peak_az": peak_az, "peak_el": peak_el, "peak_km": peak_km,
        "earth_az": (lo, hi),
        "earth_el": (float(e_el.min()), float(e_el.max())),
        "ridge_toward_earth": (float(earth_ridge.min()), float(earth_ridge.max())),
        "sun_el_max": float(s_el.max()),
        "far_bins_pct": float(100.0 * np.mean(dist > MESH_KM)),
    }


def plot_site(site, mask, ang, path):
    h720 = np.asarray(mask["elev_deg_720_by_mast"][MAST], float)
    dist = np.asarray(mask["horizon_dist_km_by_mast"][MAST], float)
    az720 = np.arange(720) * 0.5
    sun_az, sun_el = np.asarray(ang["sun_az"]), np.asarray(ang["sun_el"])
    e_az, e_el = np.asarray(ang["earth_az"]), np.asarray(ang["earth_el"])

    fig, ax = plt.subplots(figsize=(11, 4.2), dpi=130)
    for b in np.nonzero(dist > MESH_KM)[0]:                   # 1-deg bins beyond the 3D mesh
        ax.axvspan(b - 0.5, b + 0.5, color="0.85", lw=0, zorder=0)
    ax.scatter(sun_az[::3], sun_el[::3], s=1.5, color="#e8a317", alpha=0.35, lw=0, label="Sun (2027, every 3 h)")
    ax.scatter(e_az[::3], e_el[::3], s=1.5, color="#2f7fd1", alpha=0.35, lw=0, label="Earth (2027, every 3 h)")
    ax.fill_between(az720, -10, h720, color="#5b5348", alpha=0.85, lw=0, zorder=2)
    ax.plot(az720, h720, color="black", lw=0.8, zorder=3, label=f"terrain horizon, {MAST} m mast")

    lo = min(h720.min(), sun_el.min(), e_el.min()) - 0.5
    hi = max(h720.max(), sun_el.max(), e_el.max()) + 0.5
    ax.set_ylim(lo, hi)
    ax.set_xlim(0, 360)
    ax.set_xticks(range(0, 361, 45))
    ax.set_xticklabels(["N 0", "45", "E 90", "135", "S 180", "225", "W 270", "315", "N 360"])
    ax.set_xlabel("azimuth (deg, clockwise from north)")
    ax.set_ylabel("elevation (deg)")
    ax.set_title(f"{site['name']}  ·  {site['lat']:.4f}, {site['lon']:.4f}  ·  "
                 f"grey bands: blocking terrain > {MESH_KM:g} km away (not in the 3D mesh)", fontsize=9)
    ax.grid(alpha=0.3, lw=0.5)
    ax.legend(loc="upper right", fontsize=7, markerscale=6, framealpha=0.9)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    sites = json.loads((DATA / "sites.json").read_text())
    lines = ["# Skyline plots (M2.1)", "",
             f"Generated by `Member2/pipeline/plot_skylines.py` from `data_out/` ({MAST} m mast, 2027). "
             "Every number below is computed from the data, not typed in.", "",
             "| Site | Highest ridge (az, elev, distance) | Earth azimuth range | Earth elevation range | "
             "Terrain toward Earth | Highest Sun | Horizon bins beyond 3D mesh |",
             "|---|---|---|---|---|---|---|"]
    for s in sites:
        mask = json.loads((DATA / "mask" / f"{s['id']}.json").read_text())
        ang = json.loads((DATA / "angles" / f"{s['id']}.json").read_text())
        plot_site(s, mask, ang, OUT / f"{s['id']}.png")
        r = site_summary(s, mask, ang)
        lines.append(
            f"| {s['name']} | {r['peak_az']:.1f}°, {r['peak_el']:.2f}°, {r['peak_km']:.1f} km | "
            f"{r['earth_az'][0]:.1f}°–{r['earth_az'][1]:.1f}° | "
            f"{r['earth_el'][0]:.2f}° to {r['earth_el'][1]:.2f}° | "
            f"{r['ridge_toward_earth'][0]:.2f}° to {r['ridge_toward_earth'][1]:.2f}° | "
            f"{r['sun_el_max']:.2f}° | {r['far_bins_pct']:.0f}% |")
        print(f"wrote docs/skylines/{s['id']}.png")
    lines += ["", "![site01](site01.png)", "![site04](site04.png)", "![site07](site07.png)",
              "![site11](site11.png)", "![site23](site23.png)"]
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote docs/skylines/README.md")


if __name__ == "__main__":
    main()
